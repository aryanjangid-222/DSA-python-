class Solution(object):
    def countCommas(self, n):
        if n < 10**3:
            return 0
        elif n < 10**6:
            return n - (10**3-1)
        elif n < 10**9:
            return (n-10**6)*2 + (10**6 - (10**3 - 2))
        elif n < 10**12:
            return (n-10**9)*3 + (10**9 - (10**6 - 1))*2 + 10**6 - (10**3 -1)
        elif n < 10**15:
            return (n-10**12)*4 + (10**12 - (10**9 -1 ))*3 + (10**9 - 10**6)*2 + 10**6 - (10**3 - 1)
        else:
            return (n-10**12)*4 + (10**12 - (10**9 -1 ))*3 + (10**9 - 10**6)*2 + 10**6 - (10**3 - 1) + 1